package win.huarun.huarunwin

import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import com.android.apksig.ApkVerifier
import org.junit.After
import org.junit.Assert.*
import org.junit.Before
import org.junit.Test
import org.junit.runner.RunWith
import java.io.File
import java.security.KeyStore
import java.security.MessageDigest
import java.security.KeyPairGenerator
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import javax.security.auth.x500.X500Principal
import java.math.BigInteger
import java.util.Date

@RunWith(AndroidJUnit4::class)
class ApkResignerTest {
    private val context = InstrumentationRegistry.getInstrumentation().targetContext
    private var preferred: String? = null
    private var known: Set<String>? = null
    private lateinit var signer: ApkResigner
    private lateinit var folder: File
    private lateinit var input: File
    private lateinit var key: Map<String, String>
    private var legacyId: String? = null

    @Before fun prepare() {
        // Remove only abandoned identities from this named test fixture.
        KeyStore.getInstance("AndroidKeyStore").apply {
            load(null)
            aliases().toList().filter { it.contains(".test-") &&
                (getCertificate(it) as? java.security.cert.X509Certificate)?.subjectX500Principal?.name == "CN=HuarunWin Legacy Key Test"
            }.forEach { deleteEntry(it) }
        }
        signer = ApkResigner(context)
        preferred = context.getSharedPreferences("apk_signing", 0).getString("preferred", null)
        known = context.getSharedPreferences("apk_signing", 0).getStringSet("known", null)?.toSet()
        folder = File(context.cacheDir, "resigner-test-" + System.nanoTime()).apply { mkdirs() }
        // A small, genuinely signed APK generated by the Android build, not a third-party app.
        input = File(InstrumentationRegistry.getInstrumentation().context.applicationInfo.sourceDir).copyTo(File(folder, "source.apk"))
        // Preserve coverage for identities created before portable-key support.
        val id = "win.huarun.apk.signing.${System.currentTimeMillis()}.test-${System.nanoTime()}"
        legacyId = id
        KeyPairGenerator.getInstance("RSA", "AndroidKeyStore").apply {
            initialize(KeyGenParameterSpec.Builder(id, KeyProperties.PURPOSE_SIGN or KeyProperties.PURPOSE_VERIFY)
                .setKeySize(2048).setDigests(KeyProperties.DIGEST_SHA1, KeyProperties.DIGEST_SHA256, KeyProperties.DIGEST_SHA512)
                .setSignaturePaddings(KeyProperties.SIGNATURE_PADDING_RSA_PKCS1, KeyProperties.SIGNATURE_PADDING_RSA_PSS)
                .setCertificateSubject(X500Principal("CN=HuarunWin Legacy Key Test"))
                .setCertificateSerialNumber(BigInteger.ONE)
                .setCertificateNotBefore(Date(System.currentTimeMillis() - 86400000L))
                .setCertificateNotAfter(Date(System.currentTimeMillis() + 365L * 86400000L)).build())
        }.generateKeyPair()
        key = signer.keys().single { it["id"] == id }.filterValues { it is String }.mapValues { it.value as String }
    }

    @After fun clean() {
        legacyId?.let { id -> KeyStore.getInstance("AndroidKeyStore").apply { load(null); deleteEntry(id) } }
        context.getSharedPreferences("apk_signing", 0).edit().putString("preferred", preferred)
            .putStringSet("known", known).remove("certificate.$legacyId").commit()
        if (::folder.isInitialized) folder.deleteRecursively()
    }

    @Test fun signsAndVerifiesIndependentCopyWithStableNonExportableKey() {
        val before = ApkResigner.sha256(input)
        val output = ApkResigner.outputFile(input)
        assertEquals(File(folder, "source-huarun-sign.apk"), output)
        val result = signer.resign(input, output, key.getValue("id"), before, key.getValue("certificateSha256"))
        assertEquals(before, ApkResigner.sha256(input))
        assertNotEquals(before, result["sha256"])
        assertEquals(ApkResigner.sha256(output), result["sha256"])
        val verification = ApkVerifier.Builder(output).setMinCheckedPlatformVersion(21).build().verify()
        assertTrue(verification.errors.toString(), verification.isVerified)
        assertTrue(verification.isVerifiedUsingV1Scheme)
        assertTrue(verification.isVerifiedUsingV2Scheme)
        assertTrue(verification.isVerifiedUsingV3Scheme)
        val digest = MessageDigest.getInstance("SHA-256").digest(verification.signerCertificates.single().encoded)
            .joinToString("") { "%02x".format(it) }
        assertEquals(key["certificateSha256"], digest)
        val oldPackage = context.packageManager.getPackageArchiveInfo(input.path, 0)!!
        val newPackage = context.packageManager.getPackageArchiveInfo(output.path, 0)!!
        assertEquals(oldPackage.packageName, newPackage.packageName)
        assertEquals(oldPackage.versionName, newPackage.versionName)
        val second = File(folder, "second.apk")
        assertEquals(digest, ApkResigner(context).resign(input, second, key.getValue("id"), before, digest)["certificateSha256"])
        val privateKey = KeyStore.getInstance("AndroidKeyStore").apply { load(null) }.getKey(key.getValue("id"), null)
        assertNull(privateKey.encoded)
        assertTrue(signer.keys().any { it["id"] == key["id"] && it["certificateSha256"] == digest })
    }

    @Test fun rejectsChangedInputAndLeavesNoDerivedPackage() {
        val output = File(folder, "signed.apk")
        assertTrue(runCatching { signer.resign(input, output, key.getValue("id"), "0".repeat(64), key.getValue("certificateSha256")) }.isFailure)
        assertFalse(output.exists())
        assertTrue(input.exists())
    }

    @Test fun renamesAndSignsNormalApkWithoutChangingItsSourceOrVersion() {
        // The target application is a normal APK, unlike the instrumentation APK.
        val original = File(context.applicationInfo.sourceDir).copyTo(File(folder, "application.apk"))
        val before = ApkResigner.sha256(original)
        val output = ApkResigner.outputFile(original)
        val target = "win.huarun.fixture.personal"
        val result = signer.resign(original, output, key.getValue("id"), before,
            key.getValue("certificateSha256"), target)
        assertEquals(before, ApkResigner.sha256(original))
        assertEquals(target, result["packageName"])
        val info = context.packageManager.getPackageArchiveInfo(output.path, 0)!!
        assertEquals(target, info.packageName)
        assertEquals(context.packageManager.getPackageArchiveInfo(original.path, 0)!!.versionName, info.versionName)
        assertTrue(ApkVerifier.Builder(output).build().verify().isVerified)
        assertFalse(File(output.path + ".part").exists())
        assertFalse(File(output.path + ".unsigned").exists())
    }

    @Test fun rejectsInvalidOriginalSignatureEvenWhenItsHashMatches() {
        java.io.RandomAccessFile(input, "rw").use { file ->
            file.seek(100)
            val byte = file.readByte().toInt()
            file.seek(100)
            file.writeByte(byte xor 1)
        }
        val output = File(folder, "signed.apk")
        assertTrue(runCatching { signer.resign(input, output, key.getValue("id"), ApkResigner.sha256(input), key.getValue("certificateSha256")) }.isFailure)
        assertFalse(output.exists())
        assertFalse(File(folder, "signed.apk.part").exists())
        assertTrue(input.exists())
    }

    @Test fun missingOrChangedKeyNeverCreatesReplacementIdentity() {
        val output = File(folder, "signed.apk")
        val before = ApkResigner.sha256(input)
        assertTrue(runCatching { signer.resign(input, output, key.getValue("id"), before, "0".repeat(64)) }.isFailure)
        KeyStore.getInstance("AndroidKeyStore").apply { load(null); deleteEntry(key.getValue("id")) }
        assertTrue(runCatching { signer.resign(input, output, key.getValue("id"), before, key.getValue("certificateSha256")) }.isFailure)
        assertFalse(output.exists())
    }

    @Test fun refusesSymbolicOutputAndTemporaryFilesWithoutChangingTheOriginal() {
        val output = ApkResigner.outputFile(input)
        val before = ApkResigner.sha256(input)
        for (path in listOf(output, File(folder, output.name + ".part"), File(folder, output.name + ".unsigned"))) {
            android.system.Os.symlink(input.path, path.path)
            try {
                assertTrue(runCatching {
                    signer.resign(input, output, key.getValue("id"), before, key.getValue("certificateSha256"))
                }.isFailure)
                assertEquals(before, ApkResigner.sha256(input))
            } finally {
                path.delete()
            }
        }
    }
}
